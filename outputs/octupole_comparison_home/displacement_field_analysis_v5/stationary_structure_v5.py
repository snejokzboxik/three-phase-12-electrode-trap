"""Local effective-potential curvature and grid minimax analysis from existing P4 fields.

No geometry, FEM mesh, FEM solve, or RF trajectory is generated by this script.
It reloads stored P4 coefficients and evaluates the existing full-domain field.
"""
from __future__ import annotations
import csv, hashlib, heapq, importlib.util, json, math, sys, time
from pathlib import Path
import numpy as np
from scipy.optimize import root

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[2]
OLD=ROOT/"outputs/octupole_comparison_home/electrode_displacement_sensitivity_v1"
sys.path.insert(0,str(OLD)); sys.path.insert(0,str(OLD/".deps"))
import field_analysis as fa
CALC=OLD/"calculations"
Q=fa.CHARGE; M=fa.ION_MASS; W=fa.OMEGA; ECH=fa.E_CHARGE; V=250.0
FACTOR=Q**2*V**2/(4*M*W**2*ECH)  # eV per |E|^2 where field is per volt

def atomic_json(path,obj):
    tmp=path.with_suffix(path.suffix+".tmp"); tmp.write_text(json.dumps(obj,indent=2,allow_nan=False)+"\n",encoding="utf-8"); tmp.replace(path)

def load(pattern,resolution):
    if resolution=="h35": dirname="radial_out_10um"
    else: dirname=f"{pattern}_h50"
    directory=CALC/dirname
    field,meta=fa.field_from_coefficients(directory/f"displaced_{resolution}.msh",directory/"p4_coefficients.npz")
    return field,meta

def pseudo_eV(field,points_m):
    _,ec,es=field.sample(np.asarray(points_m,float).reshape(-1,2))
    return FACTOR*(np.sum(ec*ec,axis=1)+np.sum(es*es,axis=1))

def local_curvature(field,point_mm,step_um):
    p=np.asarray(point_mm,float)*1e-3; h=step_um*1e-6
    def f(xy): return float(pseudo_eV(field,np.asarray(xy).reshape(1,2))[0])
    f0=f(p); ex=np.array([h,0.]); ey=np.array([0.,h])
    fpx,fmx,fpy,fmy=f(p+ex),f(p-ex),f(p+ey),f(p-ey)
    g=np.array([(fpx-fmx)/(2*h),(fpy-fmy)/(2*h)])
    hxx=(fpx-2*f0+fmx)/(h*h); hyy=(fpy-2*f0+fmy)/(h*h)
    hxy=(f(p+ex+ey)-f(p+ex-ey)-f(p-ex+ey)+f(p-ex-ey))/(4*h*h)
    H=np.array([[hxx,hxy],[hxy,hyy]])
    eig=np.linalg.eigvalsh(H)
    return {"position_mm":p.tolist(),"step_um":step_um,"U_eff_eV":f0,
        "gradient_norm_eV_per_m":float(np.linalg.norm(g)),"hessian_eV_per_mm2":(H*1e-6).tolist(),
        "curvature_eigenvalues_eV_per_mm2":(eig*1e-6).tolist(),
        "positive_curvature_in_both_directions":bool(np.all(eig>0))}

def gradient_eV_per_mm(field,point_mm,step_um=5.0):
    p=np.asarray(point_mm,float)*1e-3; h=step_um*1e-6
    pts=np.array([p+[h,0],p-[h,0],p+[0,h],p-[0,h]])
    vals=pseudo_eV(field,pts)
    # Convert derivative from per metre to per millimetre.
    return np.array([(vals[0]-vals[1])/(2*h),(vals[2]-vals[3])/(2*h)])*1e-3

def basin_barrier(field,spacing_mm,start_mm,target_mm):
    axis=np.arange(-1.2,1.2000001,spacing_mm)
    xx,yy=np.meshgrid(axis,axis,indexing="xy")
    mask=xx*xx+yy*yy<=1.2**2
    pts=np.column_stack((xx[mask],yy[mask]))*1e-3
    vals=np.full(xx.shape,np.inf); vals[mask]=pseudo_eV(field,pts)
    def nearest(p):
        ij=np.unravel_index(np.argmin((xx-p[0])**2+(yy-p[1])**2+np.where(mask,0,1e9)),xx.shape)
        return ij[0]*len(axis)+ij[1]
    start=nearest(start_mm); target=nearest(target_mm)
    flat=vals.ravel(); n=flat.size; best=np.full(n,np.inf); parent=np.full(n,-1,dtype=np.int64)
    best[start]=flat[start]; queue=[(best[start],start)]; dims=xx.shape
    while queue:
        cost,u=heapq.heappop(queue)
        if cost!=best[u]: continue
        if u==target: break
        iy,ix=divmod(u,dims[1])
        for dy in (-1,0,1):
            for dx in (-1,0,1):
                if not(dx or dy): continue
                jy,jx=iy+dy,ix+dx
                if 0<=jy<dims[0] and 0<=jx<dims[1]:
                    vix=jy*dims[1]+jx
                    if not mask[jy,jx]: continue
                    cand=max(cost,flat[vix])
                    if cand<best[vix]: best[vix]=cand; parent[vix]=u; heapq.heappush(queue,(cand,vix))
    if not np.isfinite(best[target]): raise RuntimeError("No grid path between minima.")
    path=[]; u=target
    while u!=-1:
        path.append(u)
        if u==start: break
        u=int(parent[u])
    path=path[::-1]; peak=max(path,key=lambda i:flat[i]); iy,ix=divmod(peak,dims[1])
    si,sj=divmod(start,dims[1]); ti,tj=divmod(target,dims[1])
    return {"grid_spacing_mm":spacing_mm,"grid_shape":list(dims),"domain":"disk r<=1.2 mm",
        "start_grid_mm":[float(xx[si,sj]),float(yy[si,sj])],"target_grid_mm":[float(xx[ti,tj]),float(yy[ti,tj])],
        "minimax_ridge_candidate_mm":[float(xx[iy,ix]),float(yy[iy,ix])],
        "minimax_path_peak_eV":float(flat[peak]),"start_grid_value_eV":float(flat[start]),
        "target_grid_value_eV":float(flat[target]),
        "barrier_above_higher_endpoint_eV":float(flat[peak]-max(flat[start],flat[target])),
        "grid_path_points":len(path),"status":"discrete grid minimax ridge; not a verified stationary saddle"}

def main():
    started=time.perf_counter(); rows=[]; barriers=[]; saddle_refinements=[]; inputs=[]
    amplitudes=(10,25,50,100)
    for amp in amplitudes:
        pattern=f"radial_out_{amp}um"
        field,meta=load(pattern,"h50"); inputs.append({"pattern":pattern,"resolution":"h50",**meta})
        diag=json.loads((CALC/f"{pattern}_h50/field_diagnostics.json").read_text(encoding="utf-8"))
        m=diag["rotating_pseudopotential_minimum"]
        if amp==10:
            point=np.array([-0.236569167,-0.377864219])
            candidates=[("global_minimum_branch_1",point),("global_minimum_mirror",[point[0],-point[1]]),
                ("secondary_local_minimum",[0.45811,0.0])]
        else:
            point=np.asarray(m["position_m"],float)*1000
            candidates=[("reported_h50_minimum",point)]
        for label,p in candidates:
            for step in (25,50,100,200):
                result=local_curvature(field,p,step)
                rows.append({"pattern":pattern,"resolution":"h50","stationary_candidate":label,**result})
        if amp==10:
            for res in ("h35","h50"):
                f,mm=load(pattern,res); inputs.append({"pattern":pattern,"resolution":res,**mm})
                minval=json.loads((OLD/"processed/effective_minimum_method_validation.json").read_text(encoding="utf-8"))
                entry=min((x for x in minval["all_methods_positions_mm"] if x["resolution"]==res and x["radius_mm"]<0.45),key=lambda x:x["E2"])
                p=np.asarray(entry["position_mm"],float)
                if res=="h35":
                    for label,q in (("global_minimum_branch_1",p),("global_minimum_mirror",[p[0],-p[1]]),("secondary_local_minimum",[0.45811,0.0])):
                        for step in (25,50,100,200):
                            rows.append({"pattern":pattern,"resolution":res,"stationary_candidate":label,**local_curvature(f,q,step)})
                    for label,guess in (("mirror-minimum connecting ridge",[-0.117,0.0]),
                                        ("global-to-secondary connecting ridge",[0.123,0.0])):
                        solved=root(lambda xy:gradient_eV_per_mm(f,xy,5.0),np.asarray(guess),method="hybr",options={"xtol":1e-8})
                        q=np.asarray(solved.x,float); checks=[local_curvature(f,q,step) for step in (10,25,50,100)]
                        ug=float(pseudo_eV(f,np.asarray(p).reshape(1,2)*1e-3)[0])
                        us=float(pseudo_eV(f,np.asarray([0.45811,0.0]).reshape(1,2)*1e-3)[0])
                        ub=float(pseudo_eV(f,q.reshape(1,2)*1e-3)[0])
                        barrier=ub-(ug if label.startswith("mirror") else max(ug,us))
                        saddle_refinements.append({"resolution":res,"pair":label,"root_success":bool(solved.success),
                            "stationary_candidate_mm":q.tolist(),"gradient_norm_eV_per_mm":float(np.linalg.norm(gradient_eV_per_mm(f,q,5.0))),
                            "U_saddle_candidate_eV":ub,"U_global_minimum_eV":ug,
                            "U_secondary_minimum_eV":us if not label.startswith("mirror") else None,
                            "barrier_above_higher_endpoint_eV":float(barrier),"curvature_checks":checks,
                            "saddle_signature_seen":all(np.prod(x["curvature_eigenvalues_eV_per_mm2"])<0 for x in checks[:3])})
                if res=="h50":
                    mirror=np.array([p[0],-p[1]])
                    secondary=np.array([0.45811,0.0])
                    for spacing in (0.05,0.025):
                        barriers.append({"resolution":res,"pair":"mirror-related global minima",**basin_barrier(f,spacing,p.tolist(),mirror.tolist())})
                        barriers.append({"resolution":res,"pair":"global minimum to secondary local minimum",**basin_barrier(f,spacing,p.tolist(),secondary.tolist())})
                    for label,guess in (("mirror-minimum connecting ridge",[-0.1125,0.0]),
                                        ("global-to-secondary connecting ridge",[0.1125,0.0])):
                        solved=root(lambda xy:gradient_eV_per_mm(f,xy,5.0),np.asarray(guess),method="hybr",options={"xtol":1e-8})
                        q=np.asarray(solved.x,float)
                        checks=[local_curvature(f,q,step) for step in (10,25,50,100)]
                        barriers.append({"resolution":"h50","pair":label,"method":"finite-difference gradient root from grid minimax ridge",
                            "root_success":bool(solved.success),"stationary_candidate_mm":q.tolist(),
                            "gradient_norm_eV_per_mm":float(np.linalg.norm(gradient_eV_per_mm(f,q,5.0))),
                            "U_saddle_candidate_eV":checks[0]["U_eff_eV"],
                            "curvature_checks":checks,
                            "saddle_signature_seen":all(np.prod(x["curvature_eigenvalues_eV_per_mm2"])<0 for x in checks[:3]),
                            "status":"candidate saddle only; finite-element interelement derivative regularity is limited"})
                        ug=float(pseudo_eV(f,p.reshape(1,2)*1e-3)[0]); us=float(pseudo_eV(f,secondary.reshape(1,2)*1e-3)[0])
                        saddle_refinements.append({"resolution":"h50","pair":label,"root_success":bool(solved.success),
                            "stationary_candidate_mm":q.tolist(),"gradient_norm_eV_per_mm":float(np.linalg.norm(gradient_eV_per_mm(f,q,5.0))),
                            "U_saddle_candidate_eV":float(pseudo_eV(f,q.reshape(1,2)*1e-3)[0]),
                            "U_global_minimum_eV":ug,"U_secondary_minimum_eV":us if label.startswith("global-to") else None,
                            "barrier_above_higher_endpoint_eV":float(pseudo_eV(f,q.reshape(1,2)*1e-3)[0]-(ug if label.startswith("mirror") else max(ug,us))),
                            "curvature_checks":checks,
                            "saddle_signature_seen":all(np.prod(x["curvature_eigenvalues_eV_per_mm2"])<0 for x in checks[:3])})
                del f
        del field
    csv_path=HERE/"local_curvature_v5.csv"
    with csv_path.open("w",encoding="utf-8",newline="") as f:
        writer=csv.DictWriter(f,fieldnames=list(rows[0]));writer.writeheader()
        for row in rows:
            out=dict(row);out["position_mm"]=json.dumps(row["position_mm"]);out["hessian_eV_per_mm2"]=json.dumps(row["hessian_eV_per_mm2"]);out["curvature_eigenvalues_eV_per_mm2"]=json.dumps(row["curvature_eigenvalues_eV_per_mm2"]);writer.writerow(out)
    result={"field_sources":inputs,"FEM_meshes_rebuilt":False,"RF_integrations_performed":False,
        "curvature_method":"Finite differences of |E_cos|^2+|E_sin|^2 converted to rotating pseudopotential energy at 250 V, 100 kHz; several spatial steps expose local mesh sensitivity.",
        "curvature_records":len(rows),"curvature_results":rows,"barrier_method":"Discrete minimax paths on existing P4-derived effective-potential samples; repeated at 50 and 25 um grid spacing.",
        "barrier_estimates":barriers,"stationary_saddle_refinements":saddle_refinements,
        "stationary_point_caveat":"P4 FEM potential is continuous, while its elementwise gradient and the squared field may have interelement jumps. The reported finite-difference Hessians characterize scale-dependent local curvature and do not prove C2 stationarity. Grid minimax ridges are not accepted as saddles without an independent stationary-point refinement.",
        "wall_seconds":time.perf_counter()-started}
    atomic_json(HERE/"stationary_structure_v5.json",result)
    print(json.dumps({"curvature_records":len(rows),"barrier_records":len(barriers),"wall_seconds":result["wall_seconds"],
        "grid_minimax": [x for x in barriers if "grid_spacing_mm" in x],
        "stationary_refinements": [x for x in barriers if "stationary_candidate_mm" in x]},indent=2))

if __name__=="__main__": main()
